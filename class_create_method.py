# Membuat Class Cat dan menambahkan method say
# Kita akan menambahkan method say yang berarti perintah untuk mencetak teks "Meong..meong"
class Cat:
    def say(self):
        print("Meong..meong")

# Membuat objek baru
cat1 = Cat()
# Mengakses method di dalam Class dari objek yang diinisiasi dari sebuah Class
cat1.say() # Meong..meong