# Membuat lists yang berisi nama-nama hewan
animals = ["Ayam", "Bebek", "Cicak"]

# Indexing dimulai dari angka 0, jadi "Bebek" (urutan kedua) diakses dengan indexing 1
print(animals[1]) # Bebek

# Negative indexing mengakses dari urutan paling akhir
# -1 = item terakhir, -2 = item kedua dari terakhir
print(animals[-1]) # Cicak
print(animals[-2]) # Bebek